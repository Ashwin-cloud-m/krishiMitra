// 3. DEMO SCORE HISTORY — Monthly score progression per applicant
// ────────────────────────────────────────────────────────────────

function buildHistory(
  applicantId: string,
  startScore: number,
  endScore: number,
  monthsBack: number = 12
): ScoreHistoryEntry[] {
  const entries: ScoreHistoryEntry[] = [];
  const now = new Date('2025-10-01');
  const increment = (endScore - startScore) / (monthsBack - 1);

  for (let i = 0; i < monthsBack; i++) {
    const d = new Date(now);
    d.setMonth(d.getMonth() - (monthsBack - 1 - i));
    const jitter = Math.round((Math.sin(i * 1.7) * 8)); // realistic small fluctuation
    entries.push({
      applicantId,
      date: d.toISOString().slice(0, 10),
      score: Math.min(900, Math.max(300, Math.round(startScore + increment * i + jitter))),
      changeReason:
        i === 0
          ? 'Initial scoring'
          : jitter > 0
          ? 'Positive payment behavior'
          : jitter < -4
          ? 'Late utility payment'
          : 'Routine model refresh',
      isDemo: true,
    });
  }
  return entries;
}

